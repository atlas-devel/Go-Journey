package switchstatement

func SwitchStatement() {
	X := "Tuesday"

	switch X {
	case "Monday":
		println("Today is Monday")
	case "Tuesday":
		println("Today is Tuesday")
	case "Wednesday":
		println("Today is Wednesday")
	case "Thursday":
		println("Today is Thursday")
	case "Friday":
		println("Today is Friday")
	}
}